#!/usr/bin/env python3
"""b184: write xnu/nmx_fw_blobs.inc - the Tiger Lake GPU firmware built into NMXGPU.kext.

    gen_fw_embedded.py <out.inc> <checksum list> [local firmware folder]

Each file comes from the local folder if given and present (e.g. /Library/NullMoth/firmware on the build Mac), else
from linux-firmware (kernel.org, then the GitLab mirror). Every file must match the SHA-256 in the checksum list
(app/Resources/nullmoth-gpu-firmware.txt). Files that cannot be fetched or do not match are left out (the driver then
reads them from /Library/NullMoth/firmware as before); with none, no .inc is written.
Intel's firmware is redistributable under its own licence (LICENSE.i915 in linux-firmware), shipped unmodified.
"""
import hashlib, os, sys, urllib.request

FILES = ["i915/tgl_dmc_ver2_12.bin", "i915/tgl_guc_70.1.1.bin", "i915/tgl_huc_7.9.3.bin"]
URLS = ["https://git.kernel.org/pub/scm/linux/kernel/git/firmware/linux-firmware.git/plain/{}",
        "https://gitlab.com/kernel-firmware/linux-firmware/-/raw/main/{}"]

out, sums = sys.argv[1], sys.argv[2]
local = sys.argv[3] if len(sys.argv) > 3 else None
want = {}
for line in open(sums):
    p = line.split()
    if len(p) == 2:
        want[p[1]] = p[0]

blobs = []
for name in FILES:
    data, src = None, None
    if local and os.path.isfile(os.path.join(local, name)):
        data, src = open(os.path.join(local, name), "rb").read(), "local"
    for u in URLS:
        if data is not None:
            break
        try:
            with urllib.request.urlopen(u.format(name), timeout=60) as r:
                data, src = r.read(), u.split("/")[2]
        except Exception as e:
            print(f"  {name}: {u.split('/')[2]}: {e}")
    if data is None:
        print(f"{name}: NOT fetched - left out")
        continue
    h = hashlib.sha256(data).hexdigest()
    if want.get(name) and want[name] != h:
        print(f"{name}: checksum {h} does not match the list ({want[name]}) - left out")
        continue
    print(f"{name}: {len(data)} bytes from {src}, sha256 {h[:16]}...{' (not in the list)' if name not in want else ''}")
    blobs.append((name, data))

if not blobs:
    if os.path.exists(out):
        os.remove(out)
    print("no firmware embedded")
    sys.exit(0)
with open(out, "w") as f:
    f.write("/* generated by gen_fw_embedded.py - do not edit */\n")
    for i, (name, data) in enumerate(blobs):
        f.write(f"static const unsigned char nmx_fw_d{i}[{len(data)}] __attribute__((aligned(64))) = {{\n")
        for k in range(0, len(data), 24):
            f.write(",".join(str(b) for b in data[k:k + 24]) + ",\n")
        f.write("};\n")
    f.write("static const nmx_fw_blob nmx_fw_blobs[] = {\n")
    for i, (name, data) in enumerate(blobs):
        f.write(f'    {{ "{name}", nmx_fw_d{i}, {len(data)} }},\n')
    f.write("};\n")
    f.write(f"static const unsigned nmx_fw_nblobs = {len(blobs)};\n")
print(f"embedded {len(blobs)} file(s), {sum(len(d) for _, d in blobs)} bytes -> {out}")
